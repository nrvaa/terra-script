const DICT: Record<Lang, Record<Key, string>> = { en, id };

let current: Lang = 'en';

export const getLang = () => current;
export const setLang = (l: Lang) => {
  current = LANGS.includes(l) ? l : 'en';
};

/** Translate a key, filling {placeholders}. */
export function t(key: Key, vars: Record<string, string | number> = {}, lang: Lang = current): string {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** English strings for server-side rendering (the static HTML is English). */
export const en_ = (key: Key) => en[key];

/**
 * Re-translate the static page:
 *  data-i18n            → textContent
 *  data-i18n-html       → innerHTML (trusted, from the dictionary)
 *  data-i18n-title      → title (+ data-title-suffix)
 *  data-i18n-placeholder→ placeholder
 *  data-i18n-aria       → aria-label
 */
export function applyI18n(root: ParentNode = document) {
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) el.textContent = t(el.dataset.i18n as Key);
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml as Key);
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]'))
    el.title = t(el.dataset.i18nTitle as Key) + (el.dataset.titleSuffix ?? '');
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]'))
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder as Key));
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-aria]'))
    el.setAttribute('aria-label', t(el.dataset.i18nAria as Key));
  document.documentElement.lang = current;
}

